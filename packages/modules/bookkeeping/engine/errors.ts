export type LedgerErrorCode =
	| "INVALID_AMOUNT"
	| "AMOUNT_TOO_LARGE"
	| "TOO_MANY_DECIMALS"
	| "INVALID_RATE"
	| "MISSING_RATE"
	| "INVALID_DATE"
	| "INVALID_TIMEZONE"
	| "INVALID_CURRENCY"
	| "EMPTY_DOCUMENT"
	| "INVALID_LINE"
	| "INVALID_TAX"
	| "UNBALANCED"
	| "TOO_FEW_LINES"
	| "ROUNDING_TOO_LARGE"
	| "BASE_CURRENCY_MISMATCH"
	| "ARCHIVED_ACCOUNT"
	| "OVER_ALLOCATED"
	| "OVERPAYMENT_NOT_CONFIRMED"
	| "UNALLOCATED_NOT_ALLOWED"
	| "BANK_AMOUNT_REQUIRED"
	| "BANK_CURRENCY_UNSUPPORTED"
	| "SPLIT_MISMATCH"
	| "CROSS_CURRENCY_TRANSFER"
	| "MANUAL_JOURNAL_FORBIDDEN_ACCOUNT"
	| "MEMO_REQUIRED"
	| "ACCOUNTS_REQUIRED"
	| "REVERSAL_OF_REVERSAL"
	| "ALREADY_REVERSED"
	| "DOCUMENT_NOT_ISSUED"
	| "DOCUMENT_HAS_SETTLEMENTS"
	| "OPENING_ACCOUNT_NOT_ALLOWED"
	| "INVALID_TARGET";

export class LedgerError extends Error {
	readonly code: LedgerErrorCode;

	constructor(code: LedgerErrorCode, message: string) {
		super(message);
		this.name = "LedgerError";
		this.code = code;
	}
}
